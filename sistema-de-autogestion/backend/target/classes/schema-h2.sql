-- ============================================================

-- -----------------------------------------------------------
-- 1. TABLA: usuario
-- -----------------------------------------------------------
CREATE TABLE IF NOT EXISTS usuario (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    email VARCHAR(150) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(20) NOT NULL CHECK (rol IN ('ADMIN','MECANICO','ALMACENERO')),
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

-- -----------------------------------------------------------
-- 2. TABLA: cliente
-- -----------------------------------------------------------
CREATE TABLE IF NOT EXISTS cliente (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    telefono VARCHAR(20),
    email VARCHAR(150),
    documento VARCHAR(20)
);

-- -----------------------------------------------------------
-- 3. TABLA: vehiculo
-- -----------------------------------------------------------
CREATE TABLE IF NOT EXISTS vehiculo (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id INT NOT NULL REFERENCES cliente(id),
    placa VARCHAR(10) UNIQUE NOT NULL,
    marca VARCHAR(50),
    modelo VARCHAR(50),
    anio INT
);

-- -----------------------------------------------------------
-- 4. TABLA: recepcion
-- -----------------------------------------------------------
CREATE TABLE IF NOT EXISTS recepcion (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehiculo_id INT NOT NULL REFERENCES vehiculo(id),
    fecha_ingreso TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    problema_reportado CLOB NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
);

-- -----------------------------------------------------------
-- 5. TABLA: diagnostico
-- -----------------------------------------------------------
CREATE TABLE IF NOT EXISTS diagnostico (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recepcion_id INT NOT NULL REFERENCES recepcion(id),
    mecanico_id INT NOT NULL REFERENCES usuario(id),
    descripcion CLOB NOT NULL,
    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- -----------------------------------------------------------
-- 6. TABLA: servicio (catalogo)
-- -----------------------------------------------------------
CREATE TABLE IF NOT EXISTS servicio (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    precio_base NUMERIC(10,2) NOT NULL
);

-- -----------------------------------------------------------
-- 7. TABLA: producto (catalogo de repuestos/insumos)
-- -----------------------------------------------------------
CREATE TABLE IF NOT EXISTS producto (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('REPUESTO','INSUMO')),
    precio_unitario NUMERIC(10,2) NOT NULL,
    stock_actual INT NOT NULL DEFAULT 0,
    stock_minimo INT NOT NULL DEFAULT 0,
    CONSTRAINT chk_stock_no_negativo CHECK (stock_actual >= 0)
);

-- -----------------------------------------------------------
-- 8. TABLA: cotizacion
-- -----------------------------------------------------------
CREATE TABLE IF NOT EXISTS cotizacion (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    diagnostico_id INT NOT NULL REFERENCES diagnostico(id),
    total NUMERIC(10,2) NOT NULL DEFAULT 0,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
        CHECK (estado IN ('PENDIENTE','APROBADA','RECHAZADA')),
    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- -----------------------------------------------------------
-- 9. TABLAS DE DETALLE
-- -----------------------------------------------------------
CREATE TABLE IF NOT EXISTS cotizacion_servicio (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cotizacion_id INT NOT NULL REFERENCES cotizacion(id),
    servicio_id INT NOT NULL REFERENCES servicio(id),
    precio NUMERIC(10,2) NOT NULL
);

CREATE TABLE IF NOT EXISTS cotizacion_producto (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cotizacion_id INT NOT NULL REFERENCES cotizacion(id),
    producto_id INT NOT NULL REFERENCES producto(id),
    cantidad_estimada INT NOT NULL,
    precio_unitario NUMERIC(10,2) NOT NULL
);

-- -----------------------------------------------------------
-- 10. TABLA: orden_trabajo
-- -----------------------------------------------------------
CREATE TABLE IF NOT EXISTS orden_trabajo (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cotizacion_id INT NOT NULL REFERENCES cotizacion(id),
    mecanico_id INT NOT NULL REFERENCES usuario(id),
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
        CHECK (estado IN ('PENDIENTE','EN_PROCESO','EN_PRUEBA','FINALIZADA','CANCELADA')),
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_fin TIMESTAMP
);

-- -----------------------------------------------------------
-- 11. TABLA: ot_producto_usado
-- -----------------------------------------------------------
CREATE TABLE IF NOT EXISTS ot_producto_usado (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_trabajo_id INT NOT NULL REFERENCES orden_trabajo(id),
    producto_id INT NOT NULL REFERENCES producto(id),
    cantidad_usada INT NOT NULL CHECK (cantidad_usada > 0)
);

-- -----------------------------------------------------------
-- 12. TABLA: inventario_movimiento
-- -----------------------------------------------------------
CREATE TABLE IF NOT EXISTS inventario_movimiento (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id INT NOT NULL REFERENCES producto(id),
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('ENTRADA','CONSUMO','AJUSTE')),
    cantidad INT NOT NULL,
    motivo VARCHAR(255),
    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- -----------------------------------------------------------
-- 13. TABLA: pago_entrega
-- -----------------------------------------------------------
CREATE TABLE IF NOT EXISTS pago_entrega (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_trabajo_id INT NOT NULL UNIQUE REFERENCES orden_trabajo(id),
    monto NUMERIC(10,2) NOT NULL,
    fecha_pago TIMESTAMP,
    fecha_entrega TIMESTAMP
);
